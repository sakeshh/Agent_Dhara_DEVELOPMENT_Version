from __future__ import annotations

import logging
import threading
import time
import uuid
from typing import Any, Dict, List, Optional
from agent.observability.models import (
    ApprovalMetrics,
    CompilerMetrics,
    DharaTelemetrySpan,
    ExecutionMetrics,
    IRMetrics,
    RouteMetrics,
)

logger = logging.getLogger("agent.observability.opentelemetry")


class OpenTelemetryExporter:
    """
    Phase 10 OpenTelemetry & Enterprise Observability for Agent Dhara.
    Collects, aggregates, and exports:
    - RouteMetrics (routing latency, classifier confidence, planner type)
    - IRMetrics (validation count, repair count, repair success rate, semantic failures)
    - CompilerMetrics (target engine, compile time, artifact size, emission status)
    - ApprovalMetrics (governance tier, approver, decision latency)
    - ExecutionMetrics (runtime, row volume, cost estimate tier, execution success)

    Provides:
    - Prometheus text exposition format (/metrics)
    - OTLP JSON export format for Azure Monitor / Application Insights / Datadog
    """

    def __init__(self, max_buffer_size: int = 1000) -> None:
        self.max_buffer_size = max_buffer_size
        self._spans: List[DharaTelemetrySpan] = []
        self._lock = threading.RLock()

        # Cumulative aggregations
        self._route_counts: Dict[str, int] = {}
        self._target_counts: Dict[str, int] = {}
        self._approval_tier_counts: Dict[str, int] = {}
        self._total_compilations = 0
        self._successful_compilations = 0
        self._total_repairs = 0
        self._successful_repairs = 0
        self._route_latencies: List[float] = []
        self._compile_latencies: List[float] = []

    def create_span(
        self,
        session_id: str,
        route: Optional[RouteMetrics] = None,
        ir: Optional[IRMetrics] = None,
        compiler: Optional[CompilerMetrics] = None,
        approval: Optional[ApprovalMetrics] = None,
        execution: Optional[ExecutionMetrics] = None,
        tags: Optional[Dict[str, str]] = None,
    ) -> DharaTelemetrySpan:
        trace_id = f"trace_{uuid.uuid4().hex[:16]}"
        span_id = f"span_{uuid.uuid4().hex[:16]}"

        span = DharaTelemetrySpan(
            trace_id=trace_id,
            span_id=span_id,
            session_id=session_id,
            timestamp=time.time(),
            route=route or RouteMetrics(),
            ir=ir or IRMetrics(),
            compiler=compiler or CompilerMetrics(),
            approval=approval or ApprovalMetrics(),
            execution=execution or ExecutionMetrics(),
            tags=tags or {},
        )
        self.record_span(span)
        return span

    def record_span(self, span: DharaTelemetrySpan) -> None:
        with self._lock:
            self._spans.append(span)
            if len(self._spans) > self.max_buffer_size:
                self._spans.pop(0)

            # Update aggregations
            r_type = span.route.route_type
            self._route_counts[r_type] = self._route_counts.get(r_type, 0) + 1

            target = span.compiler.target
            self._target_counts[target] = self._target_counts.get(target, 0) + 1

            tier = span.approval.approval_tier
            self._approval_tier_counts[tier] = self._approval_tier_counts.get(tier, 0) + 1

            self._total_compilations += 1
            if span.compiler.success:
                self._successful_compilations += 1

            self._total_repairs += span.ir.repair_count
            if span.ir.repair_success:
                self._successful_repairs += span.ir.repair_count

            self._route_latencies.append(span.route.route_latency_ms)
            self._compile_latencies.append(span.compiler.compile_time)

    def export_prometheus(self) -> str:
        """Generates Prometheus standard text format."""
        with self._lock:
            lines: List[str] = [
                "# HELP dhara_compilations_total Total compiler generation executions.",
                "# TYPE dhara_compilations_total counter",
                f'dhara_compilations_total{{status="success"}} {self._successful_compilations}',
                f'dhara_compilations_total{{status="failed"}} {self._total_compilations - self._successful_compilations}',
                "",
                "# HELP dhara_route_requests_total Total intent routing classifications by route.",
                "# TYPE dhara_route_requests_total counter",
            ]
            for r_type, count in self._route_counts.items():
                lines.append(f'dhara_route_requests_total{{route="{r_type}"}} {count}')

            lines.extend([
                "",
                "# HELP dhara_target_artifacts_total Total code artifacts generated by compiler target.",
                "# TYPE dhara_target_artifacts_total counter",
            ])
            for target, count in self._target_counts.items():
                lines.append(f'dhara_target_artifacts_total{{target="{target}"}} {count}')

            lines.extend([
                "",
                "# HELP dhara_approval_tiers_total Total pipelines evaluated by governance approval tier.",
                "# TYPE dhara_approval_tiers_total counter",
            ])
            for tier, count in self._approval_tier_counts.items():
                lines.append(f'dhara_approval_tiers_total{{tier="{tier}"}} {count}')

            lines.extend([
                "",
                "# HELP dhara_repairs_total Total self-healing repairs executed.",
                "# TYPE dhara_repairs_total counter",
                f'dhara_repairs_total{{status="healed"}} {self._successful_repairs}',
                f'dhara_repairs_total{{status="unresolved"}} {self._total_repairs - self._successful_repairs}',
            ])

            avg_route_lat = (sum(self._route_latencies) / len(self._route_latencies)) if self._route_latencies else 0.0
            avg_comp_lat = (sum(self._compile_latencies) / len(self._compile_latencies)) if self._compile_latencies else 0.0

            lines.extend([
                "",
                "# HELP dhara_route_latency_ms_avg Average intent routing latency in milliseconds.",
                "# TYPE dhara_route_latency_ms_avg gauge",
                f"dhara_route_latency_ms_avg {avg_route_lat:.2f}",
                "",
                "# HELP dhara_compile_time_seconds_avg Average compiler compilation duration in seconds.",
                "# TYPE dhara_compile_time_seconds_avg gauge",
                f"dhara_compile_time_seconds_avg {avg_comp_lat:.4f}",
            ])
            return "\n".join(lines) + "\n"

    def export_otlp_json(self) -> Dict[str, Any]:
        """Generates OpenTelemetry Protocol (OTLP) resourceSpans JSON structure."""
        with self._lock:
            spans_payload: List[Dict[str, Any]] = []
            for s in self._spans[-50:]:  # export last 50 spans
                start_nano = int(s.timestamp * 1_000_000_000)
                end_nano = start_nano + int(s.compiler.compile_time * 1_000_000_000)

                spans_payload.append({
                    "traceId": s.trace_id,
                    "spanId": s.span_id,
                    "name": f"CompilerPipeline/{s.compiler.target}",
                    "kind": "SPAN_KIND_INTERNAL",
                    "startTimeUnixNano": str(start_nano),
                    "endTimeUnixNano": str(end_nano),
                    "attributes": [
                        {"key": "session.id", "value": {"stringValue": s.session_id}},
                        {"key": "route.type", "value": {"stringValue": s.route.route_type}},
                        {"key": "route.latency_ms", "value": {"doubleValue": s.route.route_latency_ms}},
                        {"key": "route.confidence", "value": {"doubleValue": s.route.confidence}},
                        {"key": "ir.validation_count", "value": {"intValue": s.ir.validation_count}},
                        {"key": "ir.repair_count", "value": {"intValue": s.ir.repair_count}},
                        {"key": "ir.repair_success", "value": {"boolValue": s.ir.repair_success}},
                        {"key": "compiler.target", "value": {"stringValue": s.compiler.target}},
                        {"key": "compiler.success", "value": {"boolValue": s.compiler.success}},
                        {"key": "approval.tier", "value": {"stringValue": s.approval.approval_tier}},
                        {"key": "approval.risk_level", "value": {"stringValue": s.approval.risk_level}},
                        {"key": "execution.cost_estimate", "value": {"stringValue": s.execution.cost_estimate}},
                        {"key": "execution.confidence_score", "value": {"doubleValue": s.execution.confidence_score}},
                    ],
                    "status": {"code": "STATUS_CODE_OK" if s.compiler.success else "STATUS_CODE_ERROR"},
                })

            return {
                "resourceSpans": [
                    {
                        "resource": {
                            "attributes": [
                                {"key": "service.name", "value": {"stringValue": "agent-dhara-compiler"}},
                                {"key": "service.version", "value": {"stringValue": "2.0.0"}},
                                {"key": "deployment.environment", "value": {"stringValue": "production"}},
                            ]
                        },
                        "scopeSpans": [
                            {
                                "scope": {"name": "agent.compiler.pipeline", "version": "2.0.0"},
                                "spans": spans_payload,
                            }
                        ],
                    }
                ]
            }

    def get_summary(self) -> Dict[str, Any]:
        with self._lock:
            total = self._total_compilations
            success_rate = (self._successful_compilations / total) if total > 0 else 1.0
            avg_route = (sum(self._route_latencies) / len(self._route_latencies)) if self._route_latencies else 0.0
            avg_compile = (sum(self._compile_latencies) / len(self._compile_latencies)) if self._compile_latencies else 0.0

            return {
                "total_compilations": total,
                "compilation_success_rate": round(success_rate, 3),
                "total_repairs": self._total_repairs,
                "successful_repairs": self._successful_repairs,
                "average_route_latency_ms": round(avg_route, 2),
                "average_compile_duration_s": round(avg_compile, 4),
                "route_breakdown": dict(self._route_counts),
                "target_breakdown": dict(self._target_counts),
                "approval_tier_breakdown": dict(self._approval_tier_counts),
            }


# Global Singleton
_GLOBAL_OTEL_EXPORTER = OpenTelemetryExporter()


def get_opentelemetry_exporter() -> OpenTelemetryExporter:
    return _GLOBAL_OTEL_EXPORTER
