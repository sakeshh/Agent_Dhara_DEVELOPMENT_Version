from __future__ import annotations

from typing import Dict, List, Optional
from agent.compiler.base.agent import BaseAgent
from agent.compiler.events.event_bus import CompilerEventType, EventBus
from agent.compiler.models.artifacts import CodeArtifact
from agent.compiler.models.context import CompilerContext
from agent.compiler.models.logical import ActionType, LogicalPlan, LogicalStep
from agent.compiler.models.physical import ExecutionEngine


class TestGenerator(BaseAgent):
    """Generates executable companion verification test suites for generated ETL pipelines."""

    def generate_python_tests(self, plan: LogicalPlan, context: CompilerContext) -> CodeArtifact:
        """Generates pytest test suite for Python/Pandas ETL."""
        test_methods: List[str] = []

        for ds_name in plan.dataset_names:
            steps = plan.get_steps_for_dataset(ds_name)
            for step in steps:
                for col in step.target_columns:
                    if step.action == ActionType.DEDUPLICATE:
                        test_methods.append(
                            f"def test_{ds_name}_{col}_no_duplicates(clean_data):\n"
                            f"    df = clean_data['{ds_name}']['clean']\n"
                            f"    assert df['{col}'].duplicated().sum() == 0, f'Duplicate records found in {col}'"
                        )
                    elif step.action == ActionType.FILL_NULLS:
                        test_methods.append(
                            f"def test_{ds_name}_{col}_no_nulls(clean_data):\n"
                            f"    df = clean_data['{ds_name}']['clean']\n"
                            f"    assert df['{col}'].isna().sum() == 0, f'Null values found in {col}'"
                        )
                    elif step.action == ActionType.RANGE_CLIP:
                        min_val = step.parameters.get("min_value")
                        max_val = step.parameters.get("max_value")
                        if min_val is not None:
                            test_methods.append(
                                f"def test_{ds_name}_{col}_min_bound(clean_data):\n"
                                f"    df = clean_data['{ds_name}']['clean']\n"
                                f"    assert (df['{col}'] < {min_val}).sum() == 0, f'Values below minimum bound {min_val} in {col}'"
                            )
                        if max_val is not None:
                            test_methods.append(
                                f"def test_{ds_name}_{col}_max_bound(clean_data):\n"
                                f"    df = clean_data['{ds_name}']['clean']\n"
                                f"    assert (df['{col}'] > {max_val}).sum() == 0, f'Values above maximum bound {max_val} in {col}'"
                            )
                    elif step.action in (ActionType.TRIM, ActionType.LOWERCASE):
                        if step.action == ActionType.LOWERCASE or "lowercase" in [op.value for op in step.fused_operations]:
                            test_methods.append(
                                f"def test_{ds_name}_{col}_is_lowercase(clean_data):\n"
                                f"    df = clean_data['{ds_name}']['clean']\n"
                                f"    # Check that strings with letters are all lowercase\n"
                                f"    str_vals = df['{col}'].dropna().astype(str)\n"
                                f"    assert all(val == val.lower() for val in str_vals if val), f'Uppercase characters found in {col}'"
                            )

        tests_body = "\n\n\n".join(test_methods) if test_methods else "# No dynamic tests required for this plan"

        content = (
            f'"""Companion verification test suite generated by Agent Dhara.\n'
            f'Pipeline ID: {plan.plan_id}\n'
            f'"""\n'
            f"import pytest\n"
            f"import pandas as pd\n"
            f"from etl_pipeline import run_pipeline\n\n\n"
            f"@pytest.fixture\n"
            f"def clean_data():\n"
            f"    # Mock sample fixture data for pipeline verification\n"
            f"    sample_inputs = {{\n"
            f"        '{ds_name}': pd.DataFrame() for ds_name in {plan.dataset_names}\n"
            f"    }}\n"
            f"    # Replace with test fixtures or executed pipeline output\n"
            f"    return run_pipeline(sample_inputs)\n\n\n"
            f"{tests_body}\n"
        )

        return CodeArtifact(
            artifact_id=f"test_{plan.plan_id}_py",
            name="test_etl_pipeline.py",
            language="python",
            content=content,
            file_extension=".py",
            is_entrypoint=False,
            metadata={"test_count": len(test_methods)},
        )

    def generate_sql_tests(self, plan: LogicalPlan, context: CompilerContext) -> CodeArtifact:
        """Generates T-SQL post-execution verification assertions."""
        assertions: List[str] = []

        for ds_name in plan.dataset_names:
            steps = plan.get_steps_for_dataset(ds_name)
            for step in steps:
                for col in step.target_columns:
                    if step.action == ActionType.DEDUPLICATE:
                        assertions.append(
                            f"-- Assert no duplicates in [{ds_name}].[{col}]\n"
                            f"IF EXISTS (\n"
                            f"    SELECT [{col}]\n"
                            f"    FROM [dbo].[{ds_name}_Staging]\n"
                            f"    GROUP BY [{col}]\n"
                            f"    HAVING COUNT(*) > 1\n"
                            f")\n"
                            f"    THROW 50001, 'Duplicate records detected in [{ds_name}].[{col}]', 1;"
                        )
                    elif step.action == ActionType.FILL_NULLS:
                        assertions.append(
                            f"-- Assert no null values in [{ds_name}].[{col}]\n"
                            f"IF EXISTS (\n"
                            f"    SELECT * FROM [dbo].[{ds_name}_Staging] WHERE [{col}] IS NULL\n"
                            f")\n"
                            f"    THROW 50002, 'Null values detected in [{ds_name}].[{col}]', 1;"
                        )
                    elif step.action == ActionType.RANGE_CLIP:
                        min_val = step.parameters.get("min_value")
                        max_val = step.parameters.get("max_value")
                        if min_val is not None:
                            assertions.append(
                                f"-- Assert values >= {min_val} in [{ds_name}].[{col}]\n"
                                f"IF EXISTS (\n"
                                f"    SELECT * FROM [dbo].[{ds_name}_Staging] WHERE [{col}] < {min_val}\n"
                                f")\n"
                                f"    THROW 50003, 'Values below minimum bound in [{ds_name}].[{col}]', 1;"
                            )
                        if max_val is not None:
                            assertions.append(
                                f"-- Assert values <= {max_val} in [{ds_name}].[{col}]\n"
                                f"IF EXISTS (\n"
                                f"    SELECT * FROM [dbo].[{ds_name}_Staging] WHERE [{col}] > {max_val}\n"
                                f")\n"
                                f"    THROW 50004, 'Values above maximum bound in [{ds_name}].[{col}]', 1;"
                            )

        assertions_body = "\n\n".join(assertions) if assertions else "-- No dynamic assertions"

        sql_content = (
            f"-- ====================================================================\n"
            f"-- Post-ETL Verification Assertions for Pipeline: {plan.plan_id}\n"
            f"-- ====================================================================\n\n"
            f"BEGIN TRANSACTION;\n"
            f"BEGIN TRY\n"
            f"{assertions_body}\n\n"
            f"    PRINT 'All post-execution verification assertions PASSED successfully.';\n"
            f"    COMMIT TRANSACTION;\n"
            f"END TRY\n"
            f"BEGIN CATCH\n"
            f"    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;\n"
            f"    THROW;\n"
            f"END CATCH;\n"
        )

        return CodeArtifact(
            artifact_id=f"test_{plan.plan_id}_sql",
            name="test_etl_assertions.sql",
            language="sql",
            content=sql_content,
            file_extension=".sql",
            is_entrypoint=False,
            metadata={"assertion_count": len(assertions)},
        )

    def execute(self, context: CompilerContext) -> CompilerContext:
        if not context.logical_plan:
            return context

        companion_test: Optional[CodeArtifact] = None
        if context.target_engine in (ExecutionEngine.PYTHON, ExecutionEngine.PYSPARK, ExecutionEngine.FABRIC, ExecutionEngine.DATABRICKS):
            companion_test = self.generate_python_tests(context.logical_plan, context)
        elif context.target_engine in (ExecutionEngine.AZURE_SQL, ExecutionEngine.ADF):
            companion_test = self.generate_sql_tests(context.logical_plan, context)

        if companion_test:
            context.metadata["companion_test_artifact"] = companion_test.model_dump()
            EventBus.get_instance().emit(
                event_type=CompilerEventType.TESTS_GENERATED,
                session_id=context.session_id,
                payload={
                    "test_artifact_name": companion_test.name,
                    "language": companion_test.language,
                },
                source_agent=self.__class__.__name__,
            )

        return context
