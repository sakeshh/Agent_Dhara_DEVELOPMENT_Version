from __future__ import annotations

from enum import Enum
from typing import Dict, List, Optional, Set
from pydantic import BaseModel, Field

from agent.compiler.schema.output_contract import GeneratedColumn, OutputSchemaContract
from agent.compiler.models.cleaning import CleaningMode


class ColumnKind(str, Enum):
    SOURCE = "source"
    CLEAN = "clean"
    AUDIT = "audit"
    INTERNAL = "internal"
    REJECTED = "rejected"
    SYSTEM = "system"


class ColumnMetadata(BaseModel):
    name: str
    kind: ColumnKind
    dtype: Optional[str] = None
    producer_step_id: Optional[str] = None
    is_consumed: bool = False
    consumed_by_steps: List[str] = Field(default_factory=list)


class ColumnLifecycleRegistry:
    """
    Tracks and validates the complete lifecycle of all columns across steps.
    Guarantees no invented columns, undefined references, or leaked internal scratch variables.
    """

    def __init__(self, dataset_id: str, mode: CleaningMode = CleaningMode.CLEANSE_WITH_AUDIT):
        self.dataset_id = dataset_id
        self.mode = mode
        self._columns: Dict[str, ColumnMetadata] = {}
        self._step_outputs: Dict[str, Set[str]] = {}

    def register_source(self, col_name: str, dtype: Optional[str] = None) -> None:
        """Registers a verified column from the underlying source schema."""
        self._columns[col_name] = ColumnMetadata(
            name=col_name,
            kind=ColumnKind.SOURCE,
            dtype=dtype,
        )

    def register_generated(
        self,
        col_name: str,
        kind: ColumnKind,
        producer_step_id: str,
        dtype: Optional[str] = None,
    ) -> None:
        """Registers a column generated by a specific transformation step."""
        self._columns[col_name] = ColumnMetadata(
            name=col_name,
            kind=kind,
            dtype=dtype,
            producer_step_id=producer_step_id,
        )
        self._step_outputs.setdefault(producer_step_id, set()).add(col_name)

    def require(self, col_name: str, consumer_step_id: str) -> None:
        """
        Validates that a column exists and is accessible before a step references it.
        Raises ValueError if column reference is unresolved.
        """
        if col_name not in self._columns:
            raise ValueError(
                f"Unresolved column reference: Step '{consumer_step_id}' references column '{col_name}', "
                f"which does not exist in dataset '{self.dataset_id}'."
            )
        col = self._columns[col_name]
        col.is_consumed = True
        if consumer_step_id not in col.consumed_by_steps:
            col.consumed_by_steps.append(consumer_step_id)

    def mark_consumed(self, col_name: str, consumer_step_id: str) -> None:
        self.require(col_name, consumer_step_id)

    def is_registered(self, col_name: str) -> bool:
        return col_name in self._columns

    def get_kind(self, col_name: str) -> Optional[ColumnKind]:
        col = self._columns.get(col_name)
        return col.kind if col else None

    def final_projection(self, preserve_source_schema: bool = True) -> List[str]:
        """
        Returns the clean, business-only projection list for final code generation.
        Explicitly excludes internal scratch columns and audit flags in CLEANSE_ONLY mode.
        """
        if self.mode == CleaningMode.CLEANSE_ONLY:
            return [
                col.name
                for col in self._columns.values()
                if col.kind == ColumnKind.SOURCE or (col.kind == ColumnKind.CLEAN and not preserve_source_schema)
            ]
        elif self.mode == CleaningMode.CLEANSE_WITH_AUDIT:
            return [
                col.name
                for col in self._columns.values()
                if col.kind in (ColumnKind.SOURCE, ColumnKind.CLEAN)
            ]
        elif self.mode == CleaningMode.AUDIT_ONLY:
            return list(self._columns.keys())
        return [
            col.name
            for col in self._columns.values()
            if col.kind in (ColumnKind.SOURCE, ColumnKind.CLEAN)
        ]

    def build_contract(self, preserve_source_schema: bool = True) -> OutputSchemaContract:
        """Builds a formal OutputSchemaContract snapshot from the registry state."""
        source_cols = [c.name for c in self._columns.values() if c.kind == ColumnKind.SOURCE]
        clean_cols = self.final_projection(preserve_source_schema=preserve_source_schema)
        audit_cols = [c.name for c in self._columns.values() if c.kind == ColumnKind.AUDIT]
        internal_cols = [c.name for c in self._columns.values() if c.kind == ColumnKind.INTERNAL]
        rejected_cols = [c.name for c in self._columns.values() if c.kind == ColumnKind.REJECTED]

        generated_cols = [
            GeneratedColumn(
                name=c.name,
                purpose=c.kind.value,
                producer_step_id=c.producer_step_id or "unknown",
                destination="clean" if c.kind == ColumnKind.CLEAN else "audit" if c.kind == ColumnKind.AUDIT else "internal",
                retained_in_final_output=(c.name in clean_cols),
                inferred_dtype=c.dtype,
            )
            for c in self._columns.values()
            if c.producer_step_id is not None
        ]

        return OutputSchemaContract(
            dataset_id=self.dataset_id,
            mode=self.mode,
            source_columns=source_cols,
            clean_columns=clean_cols,
            audit_columns=audit_cols,
            rejected_columns=rejected_cols,
            internal_columns=internal_cols,
            generated_columns=generated_cols,
            preserve_source_schema=preserve_source_schema,
        )

    def validate_lifecycle(self) -> tuple[bool, List[str]]:
        """Ensures all referenced columns were created and internal scratch columns are not leaked."""
        errors = []
        for name, meta in self._columns.items():
            if meta.kind == ColumnKind.INTERNAL and meta.name in self.final_projection():
                errors.append(f"Internal temporary column '{name}' was not dropped before final projection.")
        return (len(errors) == 0, errors)
