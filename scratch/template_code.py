    _dup_w = _DedupWindow.partitionBy(F.xxhash64(*_data_cols) if _data_cols else F.lit(1)).orderBy(F.lit(1))
    out = out.withColumn('_is_duplicate_row', (F.row_number().over(_dup_w) > 1).cast('boolean'))
    _dup_count = out.filter(F.col('_is_duplicate_row')).count()
    logger.warning('deduplicate [row-level]: %d potential duplicate rows flagged (NOT dropped -- manual review required)', _dup_count)
    # Step: deduplicate on factory_id, inspection_date
    # Business-key deduplication based on: factory_id, inspection_date
    # GOVERNANCE: Emitting flag column '_is_duplicate_factory_id_inspection_date' instead of hard-dropping rows.
    # Hard-drop (row_number()==1 filter) destroys data silently -- rows never reach quarantine.
    # Review flagged rows in the quarantine table before deciding to remove them.
    from pyspark.sql import Window
    _w = Window.partitionBy('factory_id', 'inspection_date').orderBy(F.lit(1))
    out = out.withColumn('_is_duplicate_factory_id_inspection_date', (F.row_number().over(_w) > 1).cast('boolean'))
    _dup_count = out.filter(F.col('_is_duplicate_factory_id_inspection_date')).count()
    logger.warning('deduplicate [factory_id, inspection_date]: %d rows flagged as duplicates -- routed to quarantine (NOT dropped)', _dup_count)
    # - Quarantine Split -
    # Separate flagged (invalid/outlier) rows from clean records for governance.
    _flag_cols = [c for c in out.columns if c.startswith('is_invalid_') or c.startswith('is_negative_') or c.endswith('_domain_flag') or c.endswith('_flagged') or c.startswith('_is_duplicate')]
    if _flag_cols:
        out = out.cache()
        from functools import reduce
        import operator
        _any_flag = reduce(operator.or_, (F.col(fc).eqNullSafe(F.lit(True)) for fc in _flag_cols))
        out_quarantine = out.filter(_any_flag)
        out = out.filter(~_any_flag)
        _quarantine_count = out_quarantine.count()
        if _quarantine_count > 0:
            logger.warning('Quarantine: %d rows routed to factory_relational_test_json_quarantine table', _quarantine_count)
            if all_dfs is not None:
                all_dfs['factory_relational_test.json_quarantine'] = out_quarantine
    return out

